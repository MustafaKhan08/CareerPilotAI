"""Pydantic schemas for AI request and response validation."""

from pydantic import BaseModel, Field, ConfigDict


# ==========================================================
# Resume Validation
# ==========================================================

class ResumeValidationResponse(BaseModel):
    """
    Response returned by the AI after validating whether
    the uploaded document is a resume.
    """

    model_config = ConfigDict(extra="forbid")

    is_resume: bool = Field(
        description="Whether the uploaded document is a professional resume."
    )

    confidence: int = Field(
        ge=0,
        le=100,
        description="AI confidence score."
    )

    reason: str = Field(
        default="",
        description="Reason when validation fails."
    )


# ==========================================================
# Resume Analysis
# ==========================================================

class ResumeAnalysisResponse(BaseModel):
    """
    Structured ATS analysis generated by the AI.
    """

    model_config = ConfigDict(extra="forbid")

    ats_score: int = Field(
        ge=0,
        le=100,
        description="Overall ATS compatibility score."
    )

    career_domain: str = Field(
        description="Most suitable career domain."
    )

    experience_level: str = Field(
        description="Detected experience level."
    )

    summary: str = Field(
        description="Overall resume summary."
    )

    skills: list[str] = Field(
        default_factory=list,
        description="Skills detected in the resume."
    )

    missing_skills: list[str] = Field(
        default_factory=list,
        description="Important missing skills."
    )

    strengths: list[str] = Field(
        default_factory=list,
        description="Resume strengths."
    )

    weaknesses: list[str] = Field(
        default_factory=list,
        description="Resume weaknesses."
    )

    suggestions: list[str] = Field(
        default_factory=list,
        description="Suggestions for improving the resume."
    )